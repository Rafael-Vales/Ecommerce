export function filterDemoProducts(filters: { category?: string; brand?: string; query?: string; tags?: string[]; limit?: number } = {}) {
  const normalize = (text: string) => text.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
  const tokens = normalize(filters.query || "").split(/\s+/).filter(Boolean);
  const matches = demoProducts.filter(p =>
    (!filters.category || p.category === filters.category) &&
    (!filters.brand || normalize(p.brand) === normalize(filters.brand)) &&
    (!filters.tags?.length || filters.tags.some(t => p.tags.some(tag => normalize(tag) === normalize(t)))) &&
    tokens.every(token => normalize([p.title, p.brand, p.description, ...p.tags, ...p.variants.map(v => v.weight)].join(" ")).includes(token))
  );
  return typeof filters.limit === "number" && Number.isFinite(filters.limit) ? matches.slice(0, Math.min(100, Math.max(1, Math.trunc(filters.limit)))) : matches;
}
